// build.cjs
const esbuild = require('esbuild');
const fs = require('fs');
const path = require('path');

const isWatch = process.argv.includes('--watch');

// Build configuration
const buildOptions = {
    entryPoints: ['src/main.ts'],
    bundle: true,
    outfile: 'dist/bundle.js',
    format: 'iife', // Immediately Invoked Function Expression for browser
    minify: false,
    target: 'es2022',
    platform: 'browser',
    sourcemap: true
};

async function build() {
    try {
        if (isWatch) {
            // Watch mode
            const context = await esbuild.context({
                ...buildOptions,
                logLevel: 'info'
            });

            await context.watch();
            console.log('Watching for changes...');
        } else {
            // Build once
            await esbuild.build(buildOptions);
            console.log('Build completed successfully');

            // Create self-contained HTML file
            await createSelfContainedHTML();
        }
    } catch (error) {
        console.error('Build failed:', error);
        process.exit(1);
    }
}

async function createSelfContainedHTML() {
    // Read the template HTML from src directory
    const templateHtml = fs.readFileSync('src/template.html', 'utf8');

    // Read the generated bundle
    const bundle = fs.readFileSync('dist/bundle.js', 'utf8');

    // Replace the script tag with the actual bundle content
    let selfContainedHtml = templateHtml.replace(
        /<script src="dist\/bundle\.js"><\/script>/,
        `<script>\n${bundle}\n</script>`
    );

    // Add a comment at the beginning to indicate this is a compiled file
    const warningComment = `<!--
    This file is auto-generated by the build process.
    DO NOT EDIT THIS FILE DIRECTLY.
    Make changes to src/template.html instead.
-->
`;

    selfContainedHtml = warningComment + selfContainedHtml;

    // Write the self-contained HTML file to root directory
    fs.writeFileSync('index.html', selfContainedHtml);
    console.log('Self-contained HTML file created at index.html in root directory');
}

build();